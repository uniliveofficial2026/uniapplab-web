export function semanticKeysFor(locale: AppLocale): Record<string, string> {
  if (locale === 'en') return { ...SEMANTIC_EN };
  if (locale === 'en-XA') {
    const out: SemanticMap = {};
    for (const [k, v] of Object.entries(SEMANTIC_EN)) out[k] = pseudoExpand(v);
    return out;
  }
  if (locale === 'ar-XB') {
    const out: SemanticMap = {};
    for (const [k, v] of Object.entries(SEMANTIC_EN)) out[k] = pseudoRtl(v);
    return out;
  }
  const explicit = BY_LOCALE[locale];
  if (explicit) {
    const out: SemanticMap = { ...SEMANTIC_EN, ...explicit };
    for (const [key, en] of Object.entries(SEMANTIC_EN)) {
      if (!out[key] || (out[key] === en && !LOAN.has(en))) {
        out[key] = glossaryTranslate(en, locale);
      }
    }
    return out;
  }
  const out: SemanticMap = {};
  for (const [key, en] of Object.entries(SEMANTIC_EN)) out[key] = glossaryTranslate(en, locale);
  return out;
}

export function isLoanwordValue(value: string): boolean {
  return LOAN.has(value);
}
