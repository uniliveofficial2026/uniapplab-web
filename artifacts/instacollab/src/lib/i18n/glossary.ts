function translateToken(token: string, locale: AppLocale): string {
  if (locale === 'en' || locale === 'en-XA' || locale === 'ar-XB') return token;
  if (GLOSSARY_KEEP.has(token)) return token;
  const table = WORD_TABLE[locale];
  return table[token] ?? table[token.replace(/:$/, '')] ?? token;
}

export function glossaryTranslate(english: string, locale: AppLocale): string {
  if (!english || locale === 'en') return english;
  const phrases = locale === 'en-XA' || locale === 'ar-XB' ? null : PHRASE_GLOSSARY[locale];
  if (phrases?.[english]) return phrases[english];
  if (phrases?.[english.trim()]) return phrases[english.trim()];

  return english.replace(/[A-Za-z][A-Za-z’'-]*/g, (word) => {
    if (GLOSSARY_KEEP.has(word)) return word;
    const exact = phrases?.[word] || (locale !== 'en-XA' && locale !== 'ar-XB' ? WORD_TABLE[locale]?.[word] : undefined);
    if (exact) return exact;
    const titled = word[0].toUpperCase() + word.slice(1).toLowerCase();
    return translateToken(titled, locale) === titled ? word : translateToken(titled, locale);
  });
}
